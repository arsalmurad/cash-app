#!/usr/bin/env bash
# Linux counterpart to the pinned Windows helper. Installs/upgrades nothing.
set -euo pipefail
if [[ "${1:-}" == --help ]]; then
  printf '%s\n' 'Usage: bash scripts/build_web_bridge.sh [--check]' \
    'Checks pinned SDKs and WASM compiler support; otherwise builds the release bridge.'
  exit 0
fi
if [[ $# -gt 1 || ( $# == 1 && "$1" != --check ) ]]; then
  printf '%s\n' 'Unknown argument; use --help.' >&2
  exit 2
fi
if [[ "$(uname -s)" != Linux || "$(uname -m)" != x86_64 ]]; then
  printf '%s\n' 'This helper requires Linux x86_64.' >&2
  exit 2
fi
cash_web_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$cash_web_root"
source scripts/codex_cloud_env.sh
for cash_web_tool in git rg readlink flutter rustc rustup cargo wasm-pack wasm-bindgen flutter_rust_bridge_codegen; do
  if ! command -v "$cash_web_tool" >/dev/null; then
    printf 'Missing prerequisite: %s. See .github/workflows/phase1-web.yml for exact pins.\n' "$cash_web_tool" >&2
    exit 2
  fi
done
cash_web_expect() {
  if [[ "$1" != "$2" ]]; then
    printf 'Expected %s; got %s. Preserve caches and investigate.\n' "$1" "$2" >&2
    exit 2
  fi
}
cash_web_flutter="$(readlink -f "$(command -v flutter)")"
cash_web_flutter_root="$(cd "$(dirname "$cash_web_flutter")/.." && pwd)"
cash_web_expect 6a19cca56475dbfba1478ee68d7bd0c2ef891da1 "$(git -C "$cash_web_flutter_root" rev-parse HEAD)"
cash_web_rust="$(rustc --version)"
if [[ "$cash_web_rust" != 'rustc 1.98.1 '* ]]; then
  printf 'Expected Rust 1.98.1; got %s.\n' "$cash_web_rust" >&2
  exit 2
fi
cash_web_expect 'wasm-pack 0.15.0' "$(wasm-pack --version)"
cash_web_expect 'wasm-bindgen 0.2.129' "$(wasm-bindgen --version)"
cash_web_expect 'flutter_rust_bridge_codegen 2.13.0' "$(flutter_rust_bridge_codegen --version)"
cash_web_expect 'rustc 1.100.0-nightly (6eeff9a52 2026-09-23)' "$(rustup run nightly-2026-09-24 rustc --version)"
if ! rustup component list --toolchain nightly-2026-09-24 --installed | rg '^rust-src$' >/dev/null; then
  printf '%s\n' 'Missing pinned nightly rust-src; see the web CI workflow.' >&2
  exit 2
fi
if ! rustup target list --toolchain nightly-2026-09-24 --installed | rg '^wasm32-unknown-unknown$' >/dev/null; then
  printf '%s\n' 'Missing pinned nightly wasm32 target; see the web CI workflow.' >&2
  exit 2
fi
cash_web_cc="${CC_wasm32_unknown_unknown:-}"
cash_web_ar="${AR_wasm32_unknown_unknown:-}"
if [[ -z "$cash_web_cc" ]]; then
  cash_web_cc="$(command -v clang || command -v clang-19 || command -v clang-18 || true)"
  if [[ -z "$cash_web_cc" && -x /workspace/toolchains/llvm/usr/lib/llvm-19/bin/clang ]]; then
    cash_web_cc=/workspace/toolchains/llvm/usr/lib/llvm-19/bin/clang
  fi
fi
if [[ -z "$cash_web_ar" ]]; then
  cash_web_ar="$(command -v llvm-ar || command -v llvm-ar-19 || command -v llvm-ar-18 || true)"
  if [[ -z "$cash_web_ar" && -x /workspace/toolchains/llvm/usr/lib/llvm-19/bin/llvm-ar ]]; then
    cash_web_ar=/workspace/toolchains/llvm/usr/lib/llvm-19/bin/llvm-ar
  fi
fi
if [[ -z "$cash_web_cc" || -z "$cash_web_ar" ]]; then
  printf '%s\n' 'Missing WASM Clang/LLVM archive tool; set CC_wasm32_unknown_unknown and AR_wasm32_unknown_unknown.' >&2
  exit 2
fi
"$cash_web_cc" --target=wasm32-unknown-unknown -matomics -mbulk-memory -c -x c -o /dev/null - </dev/null
"$cash_web_cc" --version
"$cash_web_ar" --version
printf '%s\n' 'Pinned WASM prerequisites verified. No packages installed or source generated by preflight.'
if [[ "${1:-}" == --check ]]; then exit 0; fi
export CC_wasm32_unknown_unknown="$cash_web_cc"
export AR_wasm32_unknown_unknown="$cash_web_ar"
export CFLAGS_wasm32_unknown_unknown="${CFLAGS_wasm32_unknown_unknown:-} -matomics -mbulk-memory"
cd app
flutter_rust_bridge_codegen build-web --rust-root ../rust/api --release \
  --wasm-pack-rustup-toolchain nightly-2026-09-24
